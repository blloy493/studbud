// api/breakdown.js
// Vercel serverless function. Deploy path: /api/breakdown
// Requires env var OPENAI_API_KEY set in the Vercel project settings.
// Abuse protection (Origin check, per-IP and global daily caps) comes from ./_lib/guard.js, which also needs
// STUDBUD_INTEREST_KV_REST_API_URL / _TOKEN. A per-user daily cap is applied below.
//
// v7: assignment type classification + hardcoded first step.
// Request:  { userId: string, brief: string, answers?: [{ question, answer }], round?: 0-2 }
// Response: { status: 'needs_info', questions: [string] }
//        or { status: 'ready', type, title, steps: [{ kind, title, detail, ... }] }
// Step kinds: 'do' | 'copy' (+ text) | 'citation' (+ style 'apa7'|'mla9', n) | 'question' (+ ask; no detail).
//
// v8: numbered-question assignments come back as an OUTLINE of 'question' steps (title + ask).
// The extension expands each one on demand:
// Expand request:  { userId, mode: 'expand', brief, label, ask? }
// Expand response: { status: 'ready', steps: [{ kind: 'do', title, detail }] }  (no setup or review step)
// Citation formatting is done in the extension (deterministic), never by the model.
// `brief` may end with a "FIGURES IN THE DOCUMENT" block (built by api/readdoc.js from an uploaded file); both prompts handle it.
// The first step is NOT generated by the model: the server prepends a fixed, trivial
// setup step chosen by the classified type.

import { guard, withinUserCap } from './_lib/guard.js';

const MIN_BRIEF = 40;
const MAX_BRIEF = 12000; // textarea text (MAX_BRIEF_CHARS = 8000 in content.js) + the figures block from api/readdoc.js (max 3000)
const MAX_ANSWERS = 6;
const MAX_ANSWER_LEN = 300;
const MAX_ROUND = 2; // max clarification rounds before the model must produce a plan
const MAX_STEPS = 30; // total, including the hardcoded first step
const MAX_ASK = 500; // length cap for a question's text ('ask')
const MAX_EXPAND_STEPS = 6; // micro-steps per expanded question
const DAILY_USER_CAP = 20;   // plan calls (incl. clarification rounds) per userId per UTC day. A guess: tune from beta data.
const DAILY_EXPAND_CAP = 60; // worksheet 'expand' calls per userId per UTC day: one per question, and worksheets can have 25 questions

