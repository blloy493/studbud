function httpError(status, message) {
  const e = new Error(message);
  e.status = status;
  return e;
}

// One OpenAI call that returns the parsed JSON object. Throws an error carrying .status on failure.
async function callModel(system, userContent, maxTokens) {
  const openaiRes = await fetch('https://api.openai.com/v1/chat/completions', {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      Authorization: `Bearer ${process.env.OPENAI_API_KEY}`,
    },
    body: JSON.stringify({
      model: 'gpt-6-luna',
      reasoning_effort: 'none', // reasoning model: skip hidden reasoning so the token cap goes to the JSON output
      messages: [
        { role: 'system', content: system },
        { role: 'user', content: userContent },
      ],
      response_format: { type: 'json_object' }, // guarantees syntactically valid JSON (object, not array)
      temperature: 0.2, // low: favors grounded, literal steps over creative/inferred ones
      max_completion_tokens: maxTokens,
    }),
  });

  if (!openaiRes.ok) {
    const errText = await openaiRes.text();
    console.error('OpenAI API error:', openaiRes.status, errText);
    throw httpError(502, 'Upstream model request failed');
  }

  const data = await openaiRes.json();
  const raw = data.choices?.[0]?.message?.content?.trim();
  try {
    return JSON.parse(raw);
  } catch {
    console.error('Failed to parse model output as JSON:', raw);
    throw httpError(502, 'Model returned unparsable output');
  }
}

// Worksheet expand: micro-steps for ONE question. No setup step, no review step, no needs_info.
async function handleExpand(res, brief, label, ask) {
  const userContent =
    `ASSIGNMENT TEXT (context only):\n${brief}\n\nQUESTION TO BREAK DOWN:\n${label}` + (ask ? `\n${ask}` : '');
  const parsed = await callModel(EXPAND_PROMPT, userContent, 900);
  const steps = (Array.isArray(parsed && parsed.steps) ? parsed.steps : [])
    .map(sanitizeStep)
    .filter(Boolean)
    .slice(0, MAX_EXPAND_STEPS)
    .map((st) => ({ kind: 'do', title: st.title, detail: st.detail }));
  if (steps.length === 0) {
    throw httpError(502, 'Model returned no usable steps');
  }
  return res.status(200).json({ status: 'ready', steps });
}

function cleanString(v, max) {
  return typeof v === 'string' ? v.trim().slice(0, max) : '';
}

function sanitizeStep(raw, index) {
  if (!raw || typeof raw !== 'object') return null;
  const title = cleanString(raw.title, 120);
  if (!title) return null;
  const detail = cleanString(raw.detail, 400);

  if (raw.kind === 'question') {
    // If the model omits "ask", fall back to the title so the client still has something to expand from.
    const ask = cleanString(raw.ask, MAX_ASK) || title;
    return { kind: 'question', title, ask };
  }
  if (raw.kind === 'copy') {
    const text = cleanString(raw.text, 1200);
    if (text) return { kind: 'copy', title, detail, text };
  }
  if (raw.kind === 'citation' && (raw.style === 'apa7' || raw.style === 'mla9')) {
    const n = Number.isInteger(raw.n) && raw.n > 0 ? raw.n : index + 1;
    return { kind: 'citation', title, detail, style: raw.style, n };
  }
  // Unknown or malformed kinds degrade to a plain action instead of failing the whole plan.
  return { kind: 'do', title, detail };
}

export default async function handler(req, res) {
  // Plan and expand calls use separate guard buckets. A worksheet is 1 plan call plus up to 25 expand calls, which
  // would otherwise exhaust the plan caps. req.body can be undefined on OPTIONS/GET; guard() rejects those itself.
  const isExpand = !!req.body && req.body.mode === 'expand';
  const guardOpts = isExpand
    ? { name: 'breakdown_expand', ipDailyCap: 1500, globalDailyCap: 4000 } // guesses: tune from beta data
    : { name: 'breakdown', ipDailyCap: 600, globalDailyCap: 1500 };
  if (!(await guard(req, res, guardOpts))) return;

  const body = req.body || {};

  const userId = typeof body.userId === 'string' ? body.userId.trim() : '';
  if (!/^[A-Za-z0-9_-]{8,64}$/.test(userId)) {
    return res.status(400).json({ error: 'Update StudBud to the latest version and try again.' });
  }

  const brief = typeof body.brief === 'string' ? body.brief.trim() : '';

  if (brief.length < MIN_BRIEF) {
    return res.status(400).json({ error: 'Paste your assignment instructions (at least a few sentences).' });
  }
  // Basic abuse guard: cap input length so a single request can't balloon cost.
  if (brief.length > MAX_BRIEF) {
    return res.status(400).json({ error: `Assignment text too long (max ${MAX_BRIEF} characters)` });
  }

  // Per-user cap runs after validation so malformed requests don't use up a student's daily calls,
  // and before the expand branch (which returns early) so expand calls are capped too.
  if (!(await withinUserCap(isExpand ? 'breakdown_expand' : 'breakdown', userId, isExpand ? DAILY_EXPAND_CAP : DAILY_USER_CAP))) {
    return res.status(429).json({ error: 'Daily limit reached. Come back tomorrow.', limit: true });
  }

  if (isExpand) {
    const label = cleanString(body.label, 120);
    const ask = cleanString(body.ask, MAX_ASK);
    if (!label) {
      return res.status(400).json({ error: 'Missing question to break down.' });
    }
    try {
      return await handleExpand(res, brief, label, ask);
    } catch (err) {
      if (err && err.status) return res.status(err.status).json({ error: err.message });
      console.error('Breakdown expand error:', err);
      return res.status(500).json({ error: 'Internal server error' });
    }
  }

  const answers = Array.isArray(body.answers)
    ? body.answers
        .slice(0, MAX_ANSWERS)
        .map((a) => ({ question: cleanString(a && a.question, MAX_ANSWER_LEN), answer: cleanString(a && a.answer, MAX_ANSWER_LEN) }))
        .filter((a) => a.question && a.answer)
    : [];
  const round = Number.isInteger(body.round) ? Math.min(Math.max(body.round, 0), MAX_ROUND) : 0;

  let userContent = `ASSIGNMENT TEXT:\n${brief}`;
  if (answers.length > 0) {
    userContent +=
      '\n\nCLARIFYING ANSWERS FROM THE STUDENT:\n' +
      answers.map((a) => `Q: ${a.question}\nA: ${a.answer}`).join('\n');
  }

  let system = SYSTEM_PROMPT + `\n\nClarification rounds already completed: ${round} of ${MAX_ROUND}.`;
  if (round >= MAX_ROUND) {
    system +=
      ' You must return status "ready" now. Where information is still missing, state your assumption in the relevant step detail.';
  }

  try {
    const parsed = await callModel(system, userContent, 5000); // up to 29 steps with details

    if (parsed && parsed.status === 'needs_info') {
      const questions = Array.isArray(parsed.questions)
        ? parsed.questions.map((q) => cleanString(q, 200)).filter(Boolean).slice(0, 3)
        : [];
      if (round >= MAX_ROUND || questions.length === 0) {
        return res.status(502).json({ error: 'Could not build a plan from the information provided' });
      }
      return res.status(200).json({ status: 'needs_info', questions });
    }

    // Reserve one slot for the hardcoded first step.
    const modelSteps = Array.isArray(parsed && parsed.steps)
      ? parsed.steps.map(sanitizeStep).filter(Boolean).slice(0, MAX_STEPS - 1)
      : [];
    if (modelSteps.length === 0) {
      return res.status(502).json({ error: 'Model returned no usable steps' });
    }

    // Whitelist the type; anything unrecognized falls back to 'other'.
    const type = VALID_TYPES.includes(parsed && parsed.type) ? parsed.type : 'other';
    const setup = SETUP_STEPS[type];
    const steps = [{ kind: 'do', title: setup.title, detail: setup.detail }, ...modelSteps];

    // Title is optional: if it's missing or malformed the client falls back to the start of the brief.
    const title = cleanString(parsed.title, 60);
    return res.status(200).json({ status: 'ready', type, title: title || undefined, steps });
  } catch (err) {
    if (err && err.status) return res.status(err.status).json({ error: err.message });
    console.error('Breakdown endpoint error:', err);
    return res.status(500).json({ error: 'Internal server error' });
  }
}
